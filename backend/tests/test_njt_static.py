def _tables():
    return (
        _parse(TRIPS, njt_static._parse_trips),
        _parse(STOP_TIMES, njt_static._parse_stop_times),
    )


def test_stop_routes_folds_through_trips():
    trips, stop_times = _tables()
    index = njt_static.derive_njt_stop_routes(trips, stop_times)
    assert index["112"] == ["1", "13"]  # NEC and Pascack Valley both call there
    assert index["109"] == ["1"]  # T4 has no route_id, so it contributes nothing
    # PORT JERVIS COMES BACK AS MAIN, and that is the feed's own answer rather than
    # a bug: Port Jervis has no route id, so its stations can only report the route
    # their trips run under. Inventing one here would be a fiction.
    assert index["125"] == ["6"]


def test_the_trip_index_is_the_15b_join_target():
    trips, _ = _tables()
    index = njt_static.build_njt_trip_index(trips)
    assert index["T1"] == {"route_id": "1", "headsign": "New York", "short_name": "3800"}
    # A narrowed projection: direction_id and service_id stay in the full parsed
    # table, so what this publishes is exactly what a realtime entity needs.
    assert set(index["T1"]) == {"route_id", "headsign", "short_name"}


def test_the_stop_schedule_is_sorted_and_carries_the_train_number():
    trips, stop_times = _tables()
    schedule = njt_static.build_njt_stop_schedule(trips, stop_times)
    at_112 = schedule["112"]
    assert [call["trip_id"] for call in at_112] == ["T1", "T3"]  # 07:00 before 08:25
    assert at_112[0]["train"] == "3800"
    assert at_112[0]["route_id"] == "1"
    at_125 = schedule["125"]
    assert at_125[0]["arrival"] == 25 * 3600 + 10 * 60  # past-midnight time preserved


def test_a_call_with_no_times_sorts_last_rather_than_first():
    """float("inf"), not 0. A timeless call sorted to 0 would sit ahead of every
    real departure, which is the wrong end of the list to be wrong at."""
    stop_times = _parse(
        "trip_id,arrival_time,departure_time,stop_id,stop_sequence\n"
        "T1,,,109,1\n"
        "T1,07:00:00,07:00:00,112,2\n"
        "T3,06:00:00,06:00:00,109,1\n",
        njt_static._parse_stop_times,
    )
    trips, _ = _tables()
    schedule = njt_static.build_njt_stop_schedule(trips, stop_times)
    assert [call["trip_id"] for call in schedule["109"]] == ["T3", "T1"]


def test_the_stop_schedule_falls_back_to_departure_when_arrival_is_blank():
    stop_times = _parse(
        "trip_id,arrival_time,departure_time,stop_id,stop_sequence\n"
        "T1,,06:00:00,109,1\n"
        "T3,07:00:00,,109,1\n",
        njt_static._parse_stop_times,
    )
    trips, _ = _tables()
    schedule = njt_static.build_njt_stop_schedule(trips, stop_times)
    assert [call["trip_id"] for call in schedule["109"]] == ["T1", "T3"]



    "route_id,service_id,trip_id,trip_headsign,direction_id,trip_short_name\n"
    "1,SVC1,T1,New York,0,3800\n"
    "6,SVC1,T2,Port Jervis,1,1600\n"
    "13,SVC1,T3,Hoboken,1,1610\n"
    ",SVC1,T4,Orphan,0,9999\n"  # no route_id: contributes nothing to the routes fold

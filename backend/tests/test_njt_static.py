@pytest.mark.parametrize(
    ("member", "what"),
    [
        ("stops.txt", "stops"),
        ("routes.txt", "routes"),
        ("trips.txt", "trips"),
        ("stop_times.txt", "stop times"),
    ],
)
def test_headers_only_stops_fails_validation(member, what):
    """FINDING 4, FROM BIRTH. A headers-only table is structurally perfect and
    parses cleanly to nothing; promoting one reaches "ready" with an empty map and
    nothing retrying. All four tables the load reads are gated, not just stops: a
    feed with stops and no trips places markers that can never carry a train, which
    is the same silent lie one table over."""
    headers_only = _members()[member].splitlines()[0] + "\n"
    with _open(_members(**{member: headers_only})) as zf:
        with pytest.raises(StaticValidationError, match=f"no usable {what}"):
            njt_static.validate_njt_archive(zf, now=NOW)


def test_a_calendar_dates_with_no_added_rows_fails_validation():
    """A headers-only calendar_dates is the finding-4 shape applied to the one
    table this feed cannot degrade around: with no calendar.txt, an empty
    calendar_dates means the publication schedules nothing at all, ever."""
    with _open(_members(**{"calendar_dates.txt": "service_id,date,exception_type\n"})) as zf:
        with pytest.raises(StaticValidationError, match="schedules no service days"):
            njt_static.validate_njt_archive(zf, now=NOW)


def test_a_calendar_dates_of_removals_only_schedules_nothing():
    """Removals do not extend a service span. A table of nothing but cancellations
    (however far in the future they reach) schedules no service, and must be
    rejected rather than read as a feed running until 2099."""
    removals = "service_id,date,exception_type\nSVC1,20991231,2\nSVC1,20991230,2\n"
    with _open(_members(**{"calendar_dates.txt": removals})) as zf:
        with pytest.raises(StaticValidationError, match="schedules no service days"):
            njt_static.validate_njt_archive(zf, now=NOW)


# --- the service-date guard, at its boundary --------------------------------


def test_service_ending_today_is_still_servable():
    """THE BOUNDARY, and the one that has to be inclusive. A feed whose last
    service day is TODAY is running trains right now; rejecting it would drop a
    working system on its final morning, which is strictly worse than serving it
    and letting the monitor's WARN band (which fired 30 days ago) do its job."""
    with _open(_members(**{"calendar_dates.txt": _calendar_dates(last_offset=0)})) as zf:
        njt_static.validate_njt_archive(zf, now=NOW)


def test_service_that_ended_yesterday_is_rejected():
    """THE HARD LINE. With no feed_info.txt there is no feed_end_date to read, so
    calendar_dates IS the expiry signal. A publication that schedules nothing for
    today or any day after cannot be served from, and accepting it would replace a
    working archive with a dead calendar."""
    expired = _calendar_dates(last_offset=-1, first_offset=-40)
    with _open(_members(**{"calendar_dates.txt": expired})) as zf:
        with pytest.raises(StaticValidationError, match="expired"):
            njt_static.validate_njt_archive(zf, now=NOW)


def test_the_guard_reads_today_in_new_york_not_in_utc():
    """A GTFS service date is a local calendar day at the agency. For five hours
    every evening (four under EDT) the UTC date is already tomorrow, so a guard
    reading UTC would declare a feed whose last service day is today EXPIRED at
    20:00 local, on the last evening it is actually serving trains.

    23:30 EDT on 2026-08-06 is 03:30 UTC on 2026-08-07. A feed ending 2026-08-06
    must still validate.
    """
    late_evening = datetime(2026, 8, 6, 23, 30, tzinfo=NYC_TZ).timestamp()
    assert datetime.fromtimestamp(late_evening, UTC).strftime("%Y%m%d") == "20260807"
    table = "service_id,date,exception_type\nSVC1,20260806,1\n"
    with _open(_members(**{"calendar_dates.txt": table})) as zf:
        njt_static.validate_njt_archive(zf, now=late_evening)


def test_the_publication_validator_runs_the_real_parse():
    """Strictly stronger than the archive validator, and the difference is the
    point: a publication with clean stops and routes but an undecodable byte in a
    table the light validator only checks for PRESENCE would otherwise be promoted
    over the last-known-good and then discarded, losing both."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, body in _members().items():
            if name == "trips.txt":
                # Bytes that are not valid UTF-8, so the table is present and
                # structurally fine but cannot be read.
                zf.writestr(name, TRIPS.encode()[:-5] + b"\xff\xfe\n")
            else:
                zf.writestr(name, body)
    with zipfile.ZipFile(io.BytesIO(buf.getvalue())) as zf:
        with pytest.raises(StaticValidationError):
            njt_static.validate_njt_publication(zf, now=NOW)



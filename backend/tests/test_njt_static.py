@golden
def test_golden_west_of_hudson_stations_carry_main_and_bergen_route_ids():
    """PORT JERVIS HAS NO ROUTE OF ITS OWN, and this is the assertion that keeps a
    later phase from quietly "fixing" that into a fiction. Its stations report the
    MAIN (6) and BERG (5) ids their trips run under, because those are the only
    route ids the feed gives them; the Port Jervis identity lives in trip_headsign
    and nowhere else."""
    with _fixture_zip() as zf:
        data = njt_static._parse_open(zf)
    index = njt_static.derive_njt_stop_routes(data["trips"], data["stop_times"])
    pj_trips = {
        trip_id
        for trip_id, trip in data["trips"].items()
        if "port jervis" in (trip["headsign"] or "").lower()
    }
    assert pj_trips, "the fixture must keep at least one Port Jervis trip"
    pj_stops = {
        call["stop_id"] for trip_id in pj_trips for call in data["stop_times"].get(trip_id, [])
    }
    routes_seen = {route for stop in pj_stops for route in index.get(stop, [])}
    assert routes_seen & {"5", "6"}, (
        f"Port Jervis stations must report MAIN/BERG, got {sorted(routes_seen)}"
    )
    # And no route in the feed is named for it.
    assert not [
        rid
        for rid, route in data["routes"].items()
        if "port jervis" in ((route["long_name"] or "") + (route["short_name"] or "")).lower()
    ]



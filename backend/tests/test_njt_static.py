def test_stops_parse_flat_with_no_wheelchair_field():
    stops = _parse(STOPS, njt_static._parse_stops)
    assert set(stops) == {"109", "112", "38", "125"}  # 160 has no usable coordinate
    assert stops["109"] == {
        "id": "109",
        "name": "New York Penn Station",
        "lat": 40.750568,
        "lon": -73.993519,
    }
    # THE ABSENCE IS THE ASSERTION. FerryStop carries a wheelchair bool because the
    # ferry feed publishes one; NJ Transit publishes no accessibility data at all,
    # and a hardcoded False would read downstream as an affirmative "not
    # accessible" the feed never said.
    assert "wheelchair" not in stops["109"]


def test_routes_carry_the_extended_type_and_a_null_text_color():
    routes = _parse(ROUTES, njt_static._parse_routes)
    assert len(routes) == 4
    # route_type 113 passes through verbatim: it is the GTFS EXTENDED "Rail
    # Service" type, not one of the classic 0-7 basic types, and anything
    # switch-casing 0-7 falls through it.
    assert {r["type"] for r in routes.values()} == {"113"}
    assert routes["13"]["short_name"] == "PASC"
    # Empty on all 12 real routes, so it must arrive as None rather than "" and
    # must not be defaulted to a contrast colour by the parser.
    assert routes["13"]["text_color"] is None


def test_trips_carry_the_train_number_and_the_headsign():
    trips = _parse(TRIPS, njt_static._parse_trips)
    # short_name IS the train number and 15b's second join key (745/745 on the probe).
    assert trips["T1"]["short_name"] == "3800"
    # The ONLY place Port Jervis is named anywhere in this feed: it has no route id.
    assert trips["T2"]["headsign"] == "Port Jervis"
    assert trips["T2"]["route_id"] == "6"  # MAIN, not a Port Jervis route
    assert trips["T4"]["route_id"] is None


def test_stop_times_keep_times_and_survive_hours_past_24():
    calls = _parse(STOP_TIMES, njt_static._parse_stop_times)
    assert [c["stop_id"] for c in calls["T1"]] == ["112", "109"]
    assert calls["T1"][0]["arrival"] == 7 * 3600
    # 25:10:00 is a real GTFS time, not a malformed one: a train departing after
    # midnight belongs to the previous service day and is published past 24h.
    assert calls["T2"][1]["arrival"] == 25 * 3600 + 10 * 60



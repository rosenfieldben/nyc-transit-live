def test_calendar_dates_counts_only_added_rows():
    """A removal says a service does NOT run that day. Counting one toward the
    service span would let a feed whose real service ended in March pass the
    staleness guard on the strength of a cancellation published for December."""
    table = (
        "service_id,date,exception_type\n"
        "SVC1,20260801,1\n"
        "SVC1,20260802,1\n"
        "SVC1,20991231,2\n"  # a removal far in the future: must NOT extend the span
        "SVC1,2026,1\n"  # malformed date: dropped
        ",20260803,1\n"  # no service_id: dropped
    )
    dates = _parse(table, njt_static._parse_calendar_dates)
    assert dates == {"SVC1": {"20260801", "20260802"}}
    assert njt_static.latest_service_date(dates) == "20260802"



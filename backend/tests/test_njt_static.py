"""Tests for the NJ Transit static GTFS loader (backend/njt_static.py).

Two layers, matching test_ferry_static.py's house discipline:

  - Synthetic tables (io.BytesIO and in-memory zips, no disk beyond tmp_path, no
    network) exercise the pure parsers, the validators, the derived indexes, and
    the loader's control flow. Every band and boundary is asserted at its edge.
  - Golden tests read the committed trimmed copy of the REAL feed under
    fixtures/njt_gtfs/ (generated by backend/scripts/gen_njt_fixture.py, trim rule
    documented there) and assert the live-verified facts: 12 routes all carrying
    route_type 113, the two identity stops, the west-of-Hudson stations carrying
    MAIN and BERG rather than a Port Jervis route id, and the trip_short_name
    train numbers 15b joins on. They skip loudly when the fixture has not been
    generated yet; in CI a missing fixture FAILS.

THE FIXTURE NEEDS CREDENTIALS TO GENERATE, which is new for this repo: NJ
Transit's archive is behind an account, so no CI job and no agent can produce it.
The goldens below are therefore dormant-and-loud until someone with a RailData
registration runs the generator and commits the result, which is exactly what
conftest.golden_fixture_guard is for.

THE SERVICE-DATE GUARD IS TESTED WITH AN INJECTED CLOCK, never the wall clock.
That is not merely tidiness: the guard compares against TODAY, so a wall-clock
test would pass or fail depending on the day it ran, and the one case worth
pinning (latest == today exactly, which must PASS) would be unreachable on all
but one day per fixture.
"""


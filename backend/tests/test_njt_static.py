def _calendar_dates(now: float = NOW, last_offset: int = 60, first_offset: int = -7) -> str:
    return (
        "service_id,date,exception_type\n"
        f"SVC1,{_ny_date(now, first_offset)},1\n"
        f"SVC1,{_ny_date(now, last_offset)},1\n"
    )


def _members(**overrides: str) -> dict[str, str]:
    """A valid NJT archive's members. NOTE what is absent: no calendar.txt and no
    feed_info.txt, because the real feed ships neither and a fixture that carried
    them would test a loader nobody wrote."""
    members = {
        "agency.txt": AGENCY,
        "routes.txt": ROUTES,
        "stops.txt": STOPS,
        "trips.txt": TRIPS,
        "stop_times.txt": STOP_TIMES,
        "calendar_dates.txt": _calendar_dates(),
        # Present and never parsed, exactly as upstream ships it (15a defers it).
        "shapes.txt": "shape_id,shape_pt_sequence,shape_pt_lat,shape_pt_lon\ns1,1,40.7,-74.0\n",
    }
    members.update(overrides)
    return members


def _zip_bytes(members: dict[str, str], drop: tuple[str, ...] = ()) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, body in members.items():
            if name not in drop:
                zf.writestr(name, body)
    return buf.getvalue()


def _open(members: dict[str, str], drop: tuple[str, ...] = ()) -> zipfile.ZipFile:
    return zipfile.ZipFile(io.BytesIO(_zip_bytes(members, drop)))


def _parse(table: str, parser):
    return parser(io.BytesIO(table.encode()))



def _ny_date(now: float, offset_days: int) -> str:
    """YYYYMMDD in New York, `offset_days` from `now`. Built by calendar
    arithmetic on the local date rather than by adding seconds, so a DST boundary
    inside the offset cannot silently move the answer by a day."""
    day = datetime.fromtimestamp(now, NYC_TZ).date() + timedelta(days=offset_days)
    return day.strftime("%Y%m%d")



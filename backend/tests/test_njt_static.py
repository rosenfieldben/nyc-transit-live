@golden
def test_golden_the_west_of_hudson_stations_are_actually_served_by_a_kept_trip():
    """Present in stops.txt is not enough: the station has to be REACHABLE in the
    fixture, or the arrivals and placement goldens have a marker with no service.

    Distinct from the test above because the two fail for different reasons. A
    station can reach stops.txt on the coat-tails of some other line's trip through
    the mandated-stop top-up, which is the fallback for a genuinely unserved
    station and is deliberately allowed; what must not happen quietly is the WHOLE
    line arriving that way, with no Port Jervis trip in the fixture at all.
    """
    with _fixture_zip() as zf:
        data = njt_static._parse_open(zf)
    by_name = {stop["name"]: stop_id for stop_id, stop in data["stops"].items()}
    pj_trips = {
        trip_id
        for trip_id, trip in data["trips"].items()
        if "port jervis" in (trip["headsign"] or "").lower()
    }
    assert pj_trips, "a trip must NAME the line, or its identity is unrecoverable"
    served = {
        call["stop_id"] for trip_id in pj_trips for call in data["stop_times"].get(trip_id, [])
    }
    unserved = [
        name
        for name in WEST_OF_HUDSON_STATIONS
        if by_name.get(name) and by_name[name] not in served
    ]
    assert not unserved, (
        f"west-of-Hudson stations {unserved} are in stops.txt but no Port-Jervis-headsigned "
        "trip in the fixture calls at them, so nothing in the fixture connects them to the line"
    )



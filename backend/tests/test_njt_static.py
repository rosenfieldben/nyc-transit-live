@pytest.fixture(autouse=True)
def _fresh_token_cache(monkeypatch):
    """A clean token cache per test. The production cache is process-wide on
    purpose (the static loader and, from 15b, the pollers must share one token),
    which makes it exactly the kind of state that leaks between tests."""
    monkeypatch.setattr(njt_auth, "TOKEN_CACHE", njt_auth.TokenCache())


def _fake_transport(zip_bytes: bytes, calls: list | None = None):
    async def transport(url, form, timeout_s):
        if calls is not None:
            calls.append((url, dict(form)))
        if url.endswith("getToken"):
            return 200, b'{"UserToken":"t1"}'
        return 200, zip_bytes

    return transport


async def test_absent_credentials_raise_before_any_disk_or_network(monkeypatch, tmp_path):
    """NOT-CONFIGURED IS A DISTINCT STATE, and it is reached before anything else
    happens: no cache read, no mint, no fetch. Collapsing it into the ordinary
    empty-dict failure would put an unconfigured deployment into a retry loop that
    can never succeed against an endpoint that would reject it anyway.

    The archive path is pointed at a file that DOES exist and is valid, so a loader
    that consulted the cache first would return data and fail this test. Serving a
    stale archive from a previous credentialed run would make /api/njt-stops answer
    while the status honestly said "not configured", which is the exact composite
    lie this codebase keeps removing.
    """
    cached = tmp_path / "gtfs_njt.zip"
    cached.write_bytes(_zip_bytes(_members()))
    monkeypatch.setattr(njt_static, "NJT_STATIC_ZIP", cached)
    monkeypatch.delenv(njt_auth.USERNAME_VAR, raising=False)
    monkeypatch.delenv(njt_auth.PASSWORD_VAR, raising=False)
    monkeypatch.setattr(njt_auth, "_httpx_post", _explodes())

    with pytest.raises(njt_auth.NjtNotConfigured):
        await njt_static.load_njt_static(now=NOW)


def _explodes():
    async def transport(url, form, timeout_s):
        raise AssertionError(f"no network is allowed here, but {url!r} was requested")

    return transport


async def test_a_good_download_parses_and_promotes(monkeypatch, tmp_path):
    monkeypatch.setenv(njt_auth.USERNAME_VAR, "rider")
    monkeypatch.setenv(njt_auth.PASSWORD_VAR, "secret")
    monkeypatch.setattr(njt_static, "NJT_STATIC_ZIP", tmp_path / "gtfs_njt.zip")
    calls: list = []
    monkeypatch.setattr(njt_auth, "_httpx_post", _fake_transport(_zip_bytes(_members()), calls))

    data = await njt_static.load_njt_static(now=NOW)

    assert set(data["stops"]) == {"109", "112", "38", "125"}
    assert len(data["routes"]) == 4
    assert njt_static.latest_service_date(data["calendar_dates"]) == _ny_date(NOW, 60)
    assert (tmp_path / "gtfs_njt.zip").exists(), "a validated publication must be promoted"
    # THE TOKEN WENT THROUGH THE DOOR. One mint, then the archive request carrying
    # the token as a FORM FIELD, which is the only shape RailData answers.
    assert [url.rsplit("/", 1)[-1] for url, _form in calls] == ["getToken", "getGTFS"]
    assert calls[1][1]["token"] == "t1"


async def test_a_bad_publication_is_rejected_and_nothing_is_promoted(monkeypatch, tmp_path):
    monkeypatch.setenv(njt_auth.USERNAME_VAR, "rider")
    monkeypatch.setenv(njt_auth.PASSWORD_VAR, "secret")
    zip_path = tmp_path / "gtfs_njt.zip"
    monkeypatch.setattr(njt_static, "NJT_STATIC_ZIP", zip_path)
    headers_only = STOPS.splitlines()[0] + "\n"
    bad = _zip_bytes(_members(**{"stops.txt": headers_only}))

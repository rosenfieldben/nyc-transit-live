async def test_a_failed_download_keeps_serving_the_cached_archive(monkeypatch, tmp_path):
    """Serving old while new is bad, INCLUDING past MAX_AGE_DAYS: the age policy
    exists to pick up upstream's corrections, so it yields to validity rather than
    dropping a working system. The cached archive already passed the service-date
    guard, so this can never serve an expired schedule."""
    monkeypatch.setenv(njt_auth.USERNAME_VAR, "rider")
    monkeypatch.setenv(njt_auth.PASSWORD_VAR, "secret")
    zip_path = tmp_path / "gtfs_njt.zip"
    good = _zip_bytes(_members())
    zip_path.write_bytes(good)
    import os

    old = NOW - njt_static.MAX_AGE_DAYS * 86400 * 2
    os.utime(zip_path, (old, old))
    monkeypatch.setattr(njt_static, "NJT_STATIC_ZIP", zip_path)

    async def failing(url, form, timeout_s):
        if url.endswith("getToken"):
            return 200, b'{"UserToken":"t1"}'
        return 503, b"upstream down"

    monkeypatch.setattr(njt_auth, "_httpx_post", failing)

    data = await njt_static.load_njt_static(now=NOW)
    assert set(data["stops"]) == {"109", "112", "38", "125"}
    assert zip_path.read_bytes() == good, "the cached archive must be byte-untouched"


async def test_an_expired_cached_archive_is_treated_as_absent(monkeypatch, tmp_path):
    """The service-date guard runs on the CACHE too, not only on a publication. A
    cached archive whose schedule expired overnight is rejected here and
    re-downloaded, rather than being served for another MAX_AGE_DAYS because its
    mtime is fresh."""
    monkeypatch.setenv(njt_auth.USERNAME_VAR, "rider")
    monkeypatch.setenv(njt_auth.PASSWORD_VAR, "secret")
    zip_path = tmp_path / "gtfs_njt.zip"
    expired = _calendar_dates(last_offset=-1, first_offset=-40)
    zip_path.write_bytes(_zip_bytes(_members(**{"calendar_dates.txt": expired})))
    monkeypatch.setattr(njt_static, "NJT_STATIC_ZIP", zip_path)
    monkeypatch.setattr(njt_auth, "_httpx_post", _fake_transport(_zip_bytes(_members())))

    data = await njt_static.load_njt_static(now=NOW)
    # The fresh (valid) publication replaced it, which only happens if the expired
    # cache was treated as absent rather than as fresh-by-mtime.
    assert njt_static.latest_service_date(data["calendar_dates"]) == _ny_date(NOW, 60)


